"""Reproducible demo scenario on the public corpus.

Runs the research agent on questions that exercise different parts of the system
(text retrieval, table lookup + Python arithmetic, figure analysis, cross-paper
multi-hop) and writes the *actual* outputs — plan, tool trace, answer, sources —
to docs/experiments/demo_output.md.

    python scripts/demo.py [--policy heuristic|llm|learned] [--out docs/experiments/demo_output.md]
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from atlas.common.config import load_config
from atlas.observability.logging import configure_logging
from atlas.runtime import AtlasRuntime

SCENARIO = [
    ("text", "What is the model dimension d_model of the Transformer, and how many attention heads does it use?"),
    ("table + compute", "By how many BLEU points does Transformer (big) outperform the ConvS2S Ensemble on EN-DE?"),
    ("figure", "In Figure 1 of the scaling laws paper, what exponent is shown for test loss as a function of dataset size?"),
    ("multi-hop", "How many more layers does BERT-Base have than the encoder stack of the base Transformer?"),
]


def render(kind: str, res) -> list[str]:
    lines = [f"## [{kind}] {res.query}", "", f"*policy `{res.policy}` · status `{res.status}` · "
             f"{len(res.tool_history)} tool calls · {res.latency_ms / 1000:.1f}s · trace `{res.trace_id}`*", "",
             "**Plan:** " + " / ".join(res.subquestions), "", "**Trace:**", ""]
    tools = iter(res.tool_history)
    for d in res.decisions:
        line = f"- router → `{d['action']}`" + (" (fallback)" if d.get("fallback") else "")
        if d["action"] not in ("answer", "replan"):
            rec = next(tools, None)
            if rec:
                args = json.dumps(rec.arguments)[:140]
                line += f" · `{rec.tool}({args})` → {'ok' if rec.ok else 'error: ' + str(rec.error)}, "
                line += f"+{rec.new_evidence} evidence, {rec.latency_ms:.0f} ms"
        lines.append(line)
    lines += ["", "**Answer:**", "", "> " + res.answer.replace("\n", "\n> "), "", "**Sources:**", ""]
    for s in res.report.get("sources", []):
        lines.append(f"- {'**' if s['cited'] else ''}[{s['marker']}] {s['label']}{'**' if s['cited'] else ''} "
                     f"({s['modality']} via {s['tool']})")
    return lines + [""]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", default=None)
    ap.add_argument("--out", default="docs/experiments/demo_output.md")
    args = ap.parse_args()
    cfg = load_config()
    configure_logging("WARNING")
    rt = AtlasRuntime(cfg)
    agent = rt.agent(args.policy)
    md = ["# Demo output (real run)", "",
          f"Generated by `scripts/demo.py` on {time.strftime('%Y-%m-%d %H:%M')} with LLM `{cfg.llm.model}` "
          f"({cfg.llm.provider}), VLM `{cfg.vlm.model}`, retrieval `{cfg.retrieval.mode}` + "
          f"{'reranker' if cfg.reranker.enabled else 'no reranker'}. Outputs are unedited.", ""]
    for kind, q in SCENARIO:
        res = agent.run(q)
        print(f"\n[{kind}] {q}\n -> {res.answer[:300]}")
        md += render(kind, res)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(md))
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
